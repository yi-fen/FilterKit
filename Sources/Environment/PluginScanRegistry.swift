import Foundation
import SwiftUI

/// Shared read-only plugin inventory snapshot, mirroring R16's
/// `PluginFeatureStore` snapshot semantics. One background scan is reused by the
/// Plugins screen and association previews; the most recent successful result is
/// retained while a later refresh runs or fails, so the existing list never
/// falls back to a full-screen loading state during a background refresh.
///
/// This registry coordinates scan timing and snapshot retention. The scanner
/// performs bounded, read-only Mach-O/plist inspection and SHA-256 hashing; it
/// does not load plugins, write files, or invoke dpkg. Optional package ownership
/// evidence is read from the dpkg database without executing package-manager tools.
private struct PluginInventoryScanOutput {
    let result: PluginScanResult
    let resolvedRootPath: String?
}

@MainActor
final class PluginScanRegistry: ObservableObject {
    static let shared = PluginScanRegistry()

    /// Most recent successful inventory. `nil` only before the first scan completes.
    @Published private(set) var result: PluginScanResult?
    /// True while a background scan is active. The UI uses this only to show an
    /// inline progress row; an existing snapshot stays visible meanwhile.
    @Published private(set) var isLoading = false
    @Published private(set) var snapshotRevision: UInt64 = 0

    private let environment: ReadOnlyEnvironmentProvider
    private var inFlight: Task<PluginInventoryScanOutput, Error>?
    private var scanGeneration = PluginScanGenerationTracker()
    private var attestationFreshnessTask: Task<Void, Never>?
    private var attestationInFlight = false
    private var pendingAttestation: (scan: PluginScanResult, generation: UInt64)?
    private var resolvedRootPath: String?
    private var lastHelperAttestationAttemptAt = Date.distantPast

    init(environment: ReadOnlyEnvironmentProvider = ReadOnlyEnvironmentProvider()) {
        self.environment = environment
        startAttestationFreshnessMonitor()
    }

    /// Helper attestation freshness is monitored independently from directory inventory.
    /// Unchanged files are re-attested from the existing snapshot; only changed file
    /// observations require a new inventory scan to refresh hashes and metadata.
    private func startAttestationFreshnessMonitor() {
        attestationFreshnessTask = Task { @MainActor [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: 5_000_000_000)
                guard let self, !Task.isCancelled else { return }
                self.expireStaleAttestationsAndRefreshIfNeeded()
            }
        }
    }

    private func expireStaleAttestationsAndRefreshIfNeeded(now: Date = Date()) {
        guard let current = result else { return }
        var updatedPlugins = current.plugins
        var inventoryMustRefresh = false
        var attestationMustRetry = false

        for index in updatedPlugins.indices {
            guard let attestation = updatedPlugins[index].helperIdentityAttestation,
                  attestation.status == .verified else { continue }
            let item = updatedPlugins[index]
            let filesUnchanged = Self.fileObservationMatches(item.dylibPath, item.dylibFileObservation)
                && Self.fileObservationMatches(item.plistPath, item.plistFileObservation)
                && Self.fileObservationMatches(item.manifestPath, item.manifestFileObservation)

            if !filesUnchanged {
                updatedPlugins[index].helperIdentityAttestation = nil
                inventoryMustRefresh = true
            } else if !attestation.isFresh(now: now) {
                // The file identity is unchanged. Expire the evidence, but reuse the
                // existing hashes/observations and perform Helper IPC only.
                updatedPlugins[index].helperIdentityAttestation = nil
                attestationMustRetry = true
            }
        }

        if inventoryMustRefresh || attestationMustRetry {
            result = PluginScanResult(scannedAt: current.scannedAt,
                scannedDirectory: current.scannedDirectory, directoryState: current.directoryState,
                plugins: updatedPlugins, issues: current.issues, isReadOnly: current.isReadOnly,
                identityConflicts: current.identityConflicts, scannedDirectories: current.scannedDirectories)
            snapshotRevision &+= 1
        }

        // File metadata changed: hashes must be regenerated by the one inventory
        // scanner before any new attestation can be trusted.
        if inventoryMustRefresh {
            PluginInventoryPerformanceDiagnostics.recordInventoryRefreshForChangedFiles()
            refresh()
            return
        }
        if attestationMustRetry {
            PluginInventoryPerformanceDiagnostics.recordAttestationOnlyRetry()
            retryAttestationFromCurrentSnapshot()
            return
        }

        // Helper-unavailable candidates are retried from the existing inventory.
        // This is IPC-only and must never trigger another directory/Mach-O/hash scan.
        let hasUnattestedCandidate = updatedPlugins.contains {
            $0.helperIdentityAttestation == nil && $0.pairingState == .paired
                && $0.filterKitPluginID != nil && $0.dylibSHA256 != nil
                && $0.plistSHA256 != nil && $0.manifestSHA256 != nil
                && $0.dylibFileObservation != nil && $0.plistFileObservation != nil
                && $0.manifestFileObservation != nil
        }
        if hasUnattestedCandidate && now.timeIntervalSince(lastHelperAttestationAttemptAt) >= 30 {
            PluginInventoryPerformanceDiagnostics.recordAttestationOnlyRetry()
            retryAttestationFromCurrentSnapshot()
        }
    }

    private func retryAttestationFromCurrentSnapshot() {
        guard !attestationInFlight, let current = result else { return }
        let generation = scanGeneration.current
        Task { @MainActor [weak self] in
            await self?.attachHelperIdentityAttestations(to: current, generation: generation)
        }
    }

    private static func fileObservationMatches(_ path: String?, _ expected: PluginScanFileObservation?) -> Bool {
        guard let path, let expected,
              let attributes = try? FileManager.default.attributesOfItem(atPath: path) else { return false }
        let size = (attributes[.size] as? NSNumber)?.uint64Value ?? 0
        let modificationDate = attributes[.modificationDate] as? Date
        let fileNumber = (attributes[.systemFileNumber] as? NSNumber)?.uint64Value
        return size == expected.fileSize
            && modificationDate == expected.modificationDate
            && fileNumber == expected.systemFileNumber
    }

    /// Warm the inventory off the foreground path. Safe to call at launch.
    func prewarm() {
        loadIfNeeded()
    }

    /// Reuse the active scan when one is running; otherwise start a background scan.
    /// A generation token prevents a slower, superseded scan from overwriting a newer
    /// refresh result when the detached scanner cannot be cancelled immediately.
    func loadIfNeeded() {
        // A successful shared snapshot is sufficient for every consumer, including
        // App Detail. Do not turn navigation into a fresh directory enumeration.
        guard result == nil, inFlight == nil else { return }
        startScan()
    }

    /// Force a fresh enumeration. Older scans are cancelled best-effort and their
    /// results are ignored even if the detached work completes after this refresh.
    func refresh() {
        inFlight?.cancel()
        inFlight = nil
        startScan()
    }

    private func startScan() {
        guard inFlight == nil else { return }
        let generation = scanGeneration.begin()
        snapshotRevision &+= 1
        isLoading = true

        let environment = environment
        PluginInventoryPerformanceDiagnostics.recordInventoryScanStarted()
        let task = Task.detached(priority: .utility) { () -> PluginInventoryScanOutput in
            let assessmentStart = DispatchTime.now().uptimeNanoseconds
            let report = environment.makeDiagnosticReport()
            PluginInventoryPerformanceDiagnostics.recordEnvironmentAssessment(
                milliseconds: PluginInventoryPerformanceDiagnostics.elapsedMilliseconds(since: assessmentStart))
            let scanner: ReadOnlyPluginScanner
            if let assessment = report.pluginDirectoryAssessment {
                let ownershipProvider = report.resolvedRootPath.map { DpkgFileOwnershipProvider(jbroot: $0) }
                scanner = ReadOnlyPluginScanner(assessmentProvider: { assessment },
                    packageOwnershipProvider: ownershipProvider)
            } else {
                scanner = ReadOnlyPluginScanner()
            }
            let scanStart = DispatchTime.now().uptimeNanoseconds
            let result = try await scanner.scanPlugins()
            PluginInventoryPerformanceDiagnostics.recordPluginDirectoryScan(
                milliseconds: PluginInventoryPerformanceDiagnostics.elapsedMilliseconds(since: scanStart))
            PluginInventoryPerformanceDiagnostics.logSummaryIfNeeded()
            return PluginInventoryScanOutput(result: result, resolvedRootPath: report.resolvedRootPath)
        }
        inFlight = task

        Task { @MainActor [weak self] in
            do {
                let output = try await task.value
                guard let self, self.scanGeneration.isCurrent(generation) else { return }
                self.result = output.result
                self.resolvedRootPath = output.resolvedRootPath
                RuntimeEventLogger.record(level: .info, module: "PluginInventory",
                    event: "plugin.inventory.scan.completed", message: "Plugin inventory scan completed.",
                    traceID: generation.description,
                    attributes: ["plugin_count": String(output.result.plugins.count),
                                 "issue_count": String(output.result.issues.count),
                                 "read_only": String(output.result.isReadOnly)],
                    activityTitle: "activity.plugin_scan_completed",
                    activityDetail: "\(output.result.plugins.count) plugins found; \(output.result.issues.count) diagnostic issues.")
                // Inventory completion is independent of Helper IPC. Publish the
                // snapshot and release the scan slot before starting attestation.
                self.inFlight = nil
                self.isLoading = false
                await self.attachHelperIdentityAttestations(to: output.result, generation: generation)
            } catch {
                RuntimeEventLogger.record(level: .error, module: "PluginInventory",
                    event: "plugin.inventory.scan.failed", message: "Plugin inventory scan failed.",
                    traceID: generation.description,
                    attributes: ["error_type": String(describing: type(of: error))],
                    activityTitle: "activity.plugin_scan_failed", activityDetail: "The previous successful inventory was retained.")
                // Retain the last successful snapshot on failure.
            }
            guard let self, self.scanGeneration.isCurrent(generation) else { return }
            self.inFlight = nil
            self.isLoading = false
        }
    }


    /// Enriches a successful read-only scan with Helper-authored identity attestations.
    /// Failure to reach Helper leaves all affected plugins unverified and read-only.
    private func attachHelperIdentityAttestations(to scanned: PluginScanResult, generation: UInt64) async {
        guard scanGeneration.isCurrent(generation) else { return }
        guard !attestationInFlight else {
            // A newer inventory may finish while an older Helper IPC is still pending.
            // Keep only the newest generation and process it after the current attempt.
            pendingAttestation = (scanned, generation)
            return
        }
        attestationInFlight = true
        defer {
            attestationInFlight = false
            if let pending = pendingAttestation {
                pendingAttestation = nil
                if scanGeneration.isCurrent(pending.generation) {
                    Task { @MainActor [weak self] in
                        await self?.attachHelperIdentityAttestations(
                            to: pending.scan, generation: pending.generation)
                    }
                }
            }
        }
        lastHelperAttestationAttemptAt = Date()
        guard let service = try? HelperPluginIdentityAttestationService.production(resolvedRootPath: resolvedRootPath) else { return }
        var enriched = scanned.plugins
        for index in enriched.indices {
            guard scanGeneration.isCurrent(generation),
                  enriched[index].helperIdentityAttestation == nil,
                  enriched[index].pairingState == .paired,
                  enriched[index].ownership != .packageManager,
                  enriched[index].dylibFileName != nil,
                  enriched[index].plistFileName != nil,
                  enriched[index].filterKitPluginID != nil,
                  enriched[index].dylibSHA256 != nil,
                  enriched[index].plistSHA256 != nil,
                  enriched[index].manifestSHA256 != nil,
                  enriched[index].dylibFileObservation != nil,
                  enriched[index].plistFileObservation != nil,
                  enriched[index].manifestFileObservation != nil else { continue }
            let attestationStart = DispatchTime.now().uptimeNanoseconds
            do {
                let attestation = try await service.attest(enriched[index])
                let elapsed = PluginInventoryPerformanceDiagnostics.elapsedMilliseconds(since: attestationStart)
                // Keep definitive rejection evidence so package-manager/foreign plugins
                // are not repeatedly queried. A transient unavailable response is omitted
                // and retried later by the bounded retry loop.
                let outcome: PluginInventoryPerformanceDiagnostics.Outcome
                switch attestation.status {
                case .verified where attestation.isVerified: outcome = .verified
                case .unavailable: outcome = .unavailable
                default: outcome = .rejected
                }
                PluginInventoryPerformanceDiagnostics.recordAttestation(milliseconds: elapsed, outcome: outcome)
                guard attestation.status != .unavailable else { continue }
                enriched[index].helperIdentityAttestation = attestation
                if attestation.isVerified {
                    // Helper proves a root-owned manifest/payload pair and re-checks
                    // package ownership. Only this trusted result promotes unknown
                    // inventory to FilterKit ownership.
                    enriched[index].ownership = .filterKit
                    let permission = PluginManagementPermission.evaluate(
                        ownership: .filterKit, pairing: enriched[index].pairingState,
                        binaryKind: enriched[index].binaryKind,
                        verifiedPluginID: attestation.pluginID?.uuidString,
                        filterConfiguration: enriched[index].filterConfiguration)
                    enriched[index].managementPermission = PluginManagementPermission.restricting(
                        permission, identityStatus: enriched[index].identityStatus,
                        ownershipConflict: enriched[index].ownershipConflict)
                } else if attestation.reasonCode == "package_manager_owned" {
                    // Helper's root-side package database proof takes precedence if
                    // the app-side inventory could not resolve the dpkg owner.
                    enriched[index].ownership = .packageManager
                    enriched[index].managementPermission = PluginManagementPermission.evaluate(
                        ownership: .packageManager, pairing: enriched[index].pairingState,
                        binaryKind: enriched[index].binaryKind, verifiedPluginID: nil,
                        filterConfiguration: enriched[index].filterConfiguration)
                }
            } catch {
                PluginInventoryPerformanceDiagnostics.recordAttestation(
                    milliseconds: PluginInventoryPerformanceDiagnostics.elapsedMilliseconds(since: attestationStart),
                    outcome: .error)
                // Fail closed: no App-side evidence is promoted when Helper is unavailable.
            }
        }
        guard scanGeneration.isCurrent(generation) else { return }
        result = PluginScanResult(scannedAt: scanned.scannedAt, scannedDirectory: scanned.scannedDirectory,
            directoryState: scanned.directoryState, plugins: enriched, issues: scanned.issues,
            isReadOnly: scanned.isReadOnly, identityConflicts: scanned.identityConflicts,
            scannedDirectories: scanned.scannedDirectories)
        snapshotRevision &+= 1
        PluginInventoryPerformanceDiagnostics.logSummaryIfNeeded()
    }

}
